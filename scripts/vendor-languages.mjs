// The serverless runtime cannot import npm packages. Bundle the pure detector
// locally, retaining its licenses, then deploy the resulting project module.
import { build } from 'rolldown';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { data } from 'franc-min/data.js';
import { expressions } from 'franc-min/expressions.js';

const packages = ['franc-min', 'trigram-utils', 'collapse-white-space', 'n-gram'];
const licenses = await Promise.all(packages.map(async name => `${name}\n${await readFile(name === 'franc-min' ? 'docs/licenses/franc-min.txt' : `node_modules/${name}/license`, 'utf8')}`));
await mkdir('tgcloud/lib/vendor', { recursive: true });
await build({
  input: 'node_modules/franc-min/index.js',
  output: {
    file: 'tgcloud/lib/vendor/franc.js', format: 'esm', minify: true,
    banner: `/*! Generated by npm run vendor:languages. Do not edit.\n${licenses.join('\n\n')}\n*/`,
  },
});
const aliases = { arb:'Arabic', azj:'Azerbaijani', ben:'Bengali', cmn:'Chinese', fuv:'Fulfulde', gaz:'Oromo', heb:'Hebrew', hms:'Hmong (Qiandong)', pbu:'Pashto', pes:'Persian', pnb:'Punjabi (Western)', skr:'Saraiki', swh:'Swahili', uzn:'Uzbek', zlm:'Malay', zsm:'Malay', npi:'Nepali' };
const codes = new Set(Object.values(data).flatMap(group => Object.keys(group)));
codes.add('heb'); // An additional script-based detector in language.js.
for (const code of Object.keys(expressions)) if (!data[code]) codes.add(code);
const names = new Intl.DisplayNames(['en'], { type: 'language' });
const labels = Object.fromEntries([...codes].sort().map(code => [code, aliases[code] || names.of(code)]));
await writeFile('tgcloud/lib/language-labels.js', '// Generated by npm run vendor:languages; public language names, no SDK imports.\nexport const LANGUAGE_LABELS = ' + JSON.stringify(labels, null, 2) + ';\n');
console.log(`Bundled franc-min 6.2.0 and ${codes.size} language labels.`);
